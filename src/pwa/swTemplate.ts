/**
 * Service worker source (plain JS string, emitted as `sw.js` by swPlugin.ts).
 * Placeholders __SW_VERSION__, __SW_PRECACHE__, __SW_ALL_ASSETS__ are replaced at build.
 *
 * Paths are relative to the SW's own location (= the app base), so the same file
 * works at the domain root (Vercel) and under /aluminum-app/ (GitHub Pages).
 *
 * Strategy:
 *  - navigation: network-first, fallback to cached index.html (offline / flaky network)
 *  - /download(.html), /login(.html) and api/*: never intercepted (always straight to
 *    the network; these pages must not be replaced by the cached app shell, and auth /
 *    download redirects must come from the server)
 *  - assets/*  : cache-first (hashed => immutable); misses (lazy CMaps/fonts) cached on demand
 *  - other precached files (icons, manifest): network-first, cache fallback
 *  - everything else: untouched (e.g. user PDFs, cross-origin)
 */
export const SW_SOURCE = `/* generated by src/pwa/swPlugin.ts — do not edit */
const VERSION = __SW_VERSION__;
const PRECACHE_FILES = __SW_PRECACHE__;
const ALL_ASSETS = __SW_ALL_ASSETS__;
const PREFIX = 'aluminum-';
const SHELL_CACHE = PREFIX + 'shell-' + VERSION;
const ASSET_CACHE = PREFIX + 'assets';
const BASE = new URL('./', self.location.href).href;
const abs = (p) => new URL(p, BASE).href;
const INDEX_URL = abs('index.html');
const PRECACHE_URLS = new Set(PRECACHE_FILES.map(abs));
const ASSET_URLS = new Set(ALL_ASSETS.map(abs));
const ASSETS_PREFIX = abs('assets/');
const API_PREFIX = abs('api/');
const BYPASS_URLS = new Set(['download', 'download/', 'download.html', 'login', 'login/', 'login.html'].map(abs));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await cache.addAll(PRECACHE_FILES.map((p) => new Request(abs(p), { cache: 'reload' })));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(PREFIX) && key !== SHELL_CACHE && key !== ASSET_CACHE) await caches.delete(key);
    }
    // Drop on-demand assets that no longer exist in this build.
    const assets = await caches.open(ASSET_CACHE);
    for (const req of await assets.keys()) {
      if (!ASSET_URLS.has(req.url)) await assets.delete(req);
    }
    if (self.registration.navigationPreload) {
      try { await self.registration.navigationPreload.enable(); } catch (_) {}
    }
    await self.clients.claim();
  })());
});

async function fromCaches(url) {
  const shell = await caches.open(SHELL_CACHE);
  const hit = await shell.match(url);
  if (hit) return hit;
  return (await caches.open(ASSET_CACHE)).match(url);
}

async function navigate(event) {
  try {
    const preload = await event.preloadResponse;
    if (preload) return preload;
    return await fetch(event.request);
  } catch (err) {
    const cached = await fromCaches(INDEX_URL);
    if (cached) return cached;
    throw err;
  }
}

async function cacheFirst(request) {
  const url = request.url.split('#')[0];
  const cached = await fromCaches(url);
  if (cached) return cached;
  const res = await fetch(request);
  if (res.ok && res.type === 'basic' && ASSET_URLS.has(url)) {
    const copy = res.clone();
    caches.open(ASSET_CACHE).then((c) => c.put(url, copy)).catch(() => {});
  }
  return res;
}

async function networkFirst(request) {
  try {
    return await fetch(request);
  } catch (err) {
    const cached = await fromCaches(request.url);
    if (cached) return cached;
    throw err;
  }
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !req.url.startsWith(BASE)) return;
  const path = url.origin + url.pathname;
  if (path.startsWith(API_PREFIX) || BYPASS_URLS.has(path)) return;
  if (req.mode === 'navigate') {
    event.respondWith(navigate(event));
  } else if (req.url.startsWith(ASSETS_PREFIX) && !req.headers.has('range')) {
    event.respondWith(cacheFirst(req));
  } else if (PRECACHE_URLS.has(url.origin + url.pathname)) {
    event.respondWith(networkFirst(req));
  }
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});
`;
